function specialBoxes(boxid, playerNumberTurn, diceNoRolled) {
  if (boxid == 0 || boxid == 10 || boxid == 20 || boxid == 30) {
    if (boxid == 0) {
      //free parking
      let InitialGreenMoney = greenMoney[playerNumberTurn - 1];
      let finalGreenMoney = InitialGreenMoney * 2;
      greenMoney[playerNumberTurn - 1] = finalGreenMoney;
    } else if (boxid == 20) {
      //go
      let InitialGreenMoney = greenMoney[playerNumberTurn - 1];
      let finalGreenMoney = InitialGreenMoney + 200;
      greenMoney[playerNumberTurn - 1] = finalGreenMoney;
    } else if (boxid == 30) {
      //jail
      greenMoney[playerNumberTurn - 1] = 0;
      redMoney[playerNumberTurn - 1] = 0;
    } else {
      //go to jail
      switch (playerNumberTurn) {
        case 1:
          player1 = "m30";
          break;
        case 2:
          player2 = "m30";
          break;
        case 3:
          player3 = "m30";
          break;
        case 4:
          player4 = "m30";
          break;
        default:
          console.log("Invalid player number");
          break;
      }
      for (let i = 0; i < boxPosition.length; i++) {
        if (boxPosition[i].boxName == "go") {
          let topValue = boxPosition[i].top;
          let leftValue = boxPosition[i].left;
          var element = document.getElementById(
            `PlayerCoin${playerNumberTurn}`
          );
          element.style.top = topValue;
          element.style.left = leftValue;
          break;
        }
      }
    }
  }
  if (boxid == 35) {
    /*
    4. Constitution Museum

      Functionality:
      Players landing here can "learn" an article.

      reduce red money by 50%
    */
    let redInital = redMoney[playerNumberTurn - 1];
    let redFinal = redInital * 0.5;
    redMoney[playerNumberTurn - 1] = redFinal;
  } else if (boxid == 5) {
    //assembly hall
    /* 
      5. Assembly Hall (Legislative Power)

        Functionality:
        Players propose a "rule change" for the game (e.g., "No penalties for landing on red boxes").

        Odd Roll: go to go and increase green money by 5%

        Even Roll: the player moves to jail
    */
    if (diceNoRolled % 2 == 1) {
      let greenInital = greenMoney[playerNumberTurn - 1];
      let greenFinal = greenInital + greenInital * 0.05;
      greenMoney[playerNumberTurn - 1] = greenFinal;
      switch (playerNumberTurn) {
        case 1:
          player1 = "m20";
          break;
        case 2:
          player2 = "m20";
          break;
        case 3:
          player3 = "m20";
          break;
        case 4:
          player4 = "m20";
          break;
        default:
          console.log("Invalid player number");
          break;
      }
      for (let i = 0; i < boxPosition.length; i++) {
        if (boxPosition[i].boxName == "go") {
          let topValue = boxPosition[i].top;
          let leftValue = boxPosition[i].left;
          var element = document.getElementById(
            `PlayerCoin${playerNumberTurn}`
          );
          element.style.top = topValue;
          element.style.left = leftValue;
          break;
        }
      }
    } else {
      switch (playerNumberTurn) {
        case 1:
          player1 = "m10";
          break;
        case 2:
          player2 = "m10";
          break;
        case 3:
          player3 = "m10";
          break;
        case 4:
          player4 = "m10";
          break;
        default:
          console.log("Invalid player number");
          break;
      }
      for (let i = 0; i < boxPosition.length; i++) {
        if (boxPosition[i].boxName == "Jail") {
          let topValue = boxPosition[i].top;
          let leftValue = boxPosition[i].left;
          var element = document.getElementById(
            `PlayerCoin${playerNumberTurn}`
          );
          element.style.top = topValue;
          element.style.left = leftValue;
          break;
        }
      }
    }
  } else if (boxid == 8) {
    //Educational Institute
    /*
    6. Educational Institute (Right to Education)

      Functionality:
      Players answer a quick multiple-choice question about Parts 3, 4, or 4A.

      odd : Move forward 2 spaces.

      even: reduce red money by 20%
    */
    if (diceNoRolled % 2 == 1) {
      switch (playerNumberTurn) {
        case 1:
          player1 = (boxid + 2) % 40;
          moveCoin(playerNumberTurn, player1);
          break;
        case 2:
          player2 = (boxid + 2) % 40;
          moveCoin(playerNumberTurn, player2);
          break;
        case 3:
          player3 = (boxid + 2) % 40;
          moveCoin(playerNumberTurn, player3);
          break;
        case 4:
          player4 = (boxid + 2) % 40;
          moveCoin(playerNumberTurn, player4);
          break;
        default:
          console.log("Invalid player number");
          break;
      }
    } else {
      let redInital = redMoney[playerNumberTurn - 1];
      let redFinal = redInital - redInital * 0.2;
      redMoney[playerNumberTurn - 1] = redFinal;
    }
  } else if (boxid == 15) {
    //environmental park
    /*
      odd no : reduce the red Money by 60%
      even no : increase the green Money by 5%
    */
    if (diceNoRolled % 2 == 1) {
      let redInital = redMoney[playerNumberTurn - 1];
      let redFinal = redInital - redInital * 0.6;
      redMoney[playerNumberTurn - 1] = redFinal;
    } else {
      let greenInital = greenMoney[playerNumberTurn - 1];
      let greenFinal = greenInital + greenInital * 0.05;
      greenMoney[playerNumberTurn - 1] = greenFinal;
    }
  } else if (boxid == 18) {
    //luxury tax
    //pay 200 for every player
    let redInital = redMoney[playerNumberTurn - 1];
    let redFinal = redInital - 200;
    redMoney[playerNumberTurn - 1] = redFinal;
    for (let i = 0; i < playerCount; i++) {
      if (i != playerNumberTurn - 1) {
        greenMoney[i] += 200;
      }
    }
  } else if (boxid == 24) {
    //income tax
    //reduce greenMoney increase redMoney by 200
    let greenInital = greenMoney[playerNumberTurn - 1];
    let greenFinal = greenInital - 200;
    greenMoney[playerNumberTurn - 1] = greenFinal;
    let redInital = redMoney[playerNumberTurn - 1];
    let redFinal = redInital + 200;
    redMoney[playerNumberTurn - 1] = redFinal;
  } else if (boxid == 25) {
    /*
      1. Panchayat Office (Local Governance)

        Functionality:
        Players landing here can "pass a resolution" by rolling a dice:

        Odd Roll: The player gets an extra green money

        Even Roll: The player must add with double the red money
    */
    if (diceNoRolled % 2 == 0) {
      let redInital = redMoney[playerNumberTurn - 1];
      let redFinal = redInital * 2;
      redMoney[playerNumberTurn - 1] = redFinal;
    } else {
      let greenInital = greenMoney[playerNumberTurn - 1];
      let greenFinal = greenInital + 1;
      greenMoney[playerNumberTurn - 1] = greenFinal;
    }
  }
}

